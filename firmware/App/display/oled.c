/* 缓冲区: 每页128列, 共8页 = 1024字节 */
static uint8_t oled_buffer[128];

static void OLED_WriteCmd(uint8_t cmd)
{
    uint8_t buf[2] = { 0x00, cmd };  /* 0x00 = 命令模式 */
    HAL_I2C_Master_Transmit(&OLED_I2C, OLED_ADDR, buf, 2, 100);
}

static void OLED_WriteData(uint8_t *data, uint16_t len)
{
    /* I2C一次最多发多少取决于HAL, 这里简单分页发送 */
    for (uint16_t i = 0; i < len; i++) {
        uint8_t buf[2] = { 0x40, data[i] };  /* 0x40 = 数据模式 */
        HAL_I2C_Master_Transmit(&OLED_I2C, OLED_ADDR, buf, 2, 100);
    }
}

static void OLED_SetCursor(uint8_t page, uint8_t col)
{
    OLED_WriteCmd(0xB0 | (page & 0x07));       /* 设置页地址 */
    OLED_WriteCmd(0x00 | (col & 0x0F));         /* 列地址低4位 */
    OLED_WriteCmd(0x10 | ((col >> 4) & 0x0F));  /* 列地址高4位 */
}

void OLED_Init(void)
{
    HAL_Delay(100);  /* 等待OLED上电 */

    OLED_WriteCmd(OLED_CMD_DISPLAY_OFF);
    OLED_WriteCmd(OLED_CMD_SET_CONTRAST);
    OLED_WriteCmd(0x7F);                        /* 对比度 0-255 */
    OLED_WriteCmd(OLED_CMD_SEG_REMAP);          /* 左右翻转(调整方向) */
    OLED_WriteCmd(OLED_CMD_COM_SCAN_DEC);       /* COM扫描从上到下 */
    OLED_WriteCmd(0xA8); OLED_WriteCmd(0x3F);   /* MUX ratio = 64 */
    OLED_WriteCmd(0xD3); OLED_WriteCmd(0x00);   /* 显示偏移 = 0 */
    OLED_WriteCmd(0xD5); OLED_WriteCmd(0x80);   /* 时钟分频 */
    OLED_WriteCmd(0xD9); OLED_WriteCmd(0xF1);   /* 预充电周期 */
    OLED_WriteCmd(0xDA); OLED_WriteCmd(0x12);   /* COM引脚配置 */
    OLED_WriteCmd(0xDB); OLED_WriteCmd(0x40);   /* VCOMH电压 */
    OLED_WriteCmd(0x8D); OLED_WriteCmd(0x14);   /* 电荷泵使能 */
    OLED_WriteCmd(0xA4);                        /* 全屏显示关闭(正常模式) */
    OLED_WriteCmd(0xA6);                        /* 正常显示(非反色) */
    OLED_WriteCmd(OLED_CMD_DISPLAY_ON);

    OLED_Clear();
}

void OLED_Clear(void)
{
    for (uint8_t page = 0; page < 8; page++) {
        OLED_SetCursor(page, 0);
        memset(oled_buffer, 0, 128);
        OLED_WriteData(oled_buffer, 128);
    }
}

void OLED_ShowString(uint8_t x, uint8_t y, const char *str)
{
    while (*str) {
        if (x > 21) { x = 0; y++; }
        if (y > 7) break;

        uint8_t idx = (uint8_t)(*str) - 32;
        if (idx < 95) {
            OLED_SetCursor(y, x * 6);
            OLED_WriteData((uint8_t *)FONT_6x8[idx], 6);
        }
        x++;
        str++;
    }
}

void OLED_ShowNum(uint8_t x, uint8_t y, int32_t num, uint8_t digits)
{
    char buf[12];
    snprintf(buf, sizeof(buf), "%*ld", digits, (long)num);
    OLED_ShowString(x, y, buf);
}

void OLED_ShowFloat(uint8_t x, uint8_t y, float num)
{
    char buf[12];
    snprintf(buf, sizeof(buf), "%.1f", num);
    OLED_ShowString(x, y, buf);
}

void OLED_RefreshDataPage(sensor_data_t *data, actuator_status_t *act)
{
    OLED_Clear();

    /* 第1行: 标题 */
    OLED_ShowString(0, 0, "Smart VegField");

    /* 第2行: 土壤湿度 */
    OLED_ShowString(0, 1, "S1:");
    OLED_ShowFloat(3, 1, data->soil_moisture[0]);
    OLED_ShowString(8, 1, "%");
    OLED_ShowString(10, 1, "S2:");
    OLED_ShowFloat(13, 1, data->soil_moisture[1]);
    OLED_ShowString(18, 1, "%");

    /* 第3行: 温湿度 */
    OLED_ShowString(0, 2, "T:");
    OLED_ShowFloat(2, 2, data->temperature);
    OLED_ShowString(8, 2, "C H:");
    OLED_ShowFloat(12, 2, data->humidity);
    OLED_ShowString(17, 2, "%");

    /* 第4行: 光照 */
    OLED_ShowString(0, 3, "Lux:");
    OLED_ShowNum(4, 3, data->lux, 5);

    /* 第5行: 执行器状态 */
    OLED_ShowString(0, 4, "Pump:");
    OLED_ShowString(7, 4, act->pump ? "ON " : "OFF");
    OLED_ShowString(11, 4, "Led:");
    OLED_ShowString(17, 4, act->led ? "ON " : "OFF");

    /* 第6行: 模式 + 风扇 */
    OLED_ShowString(0, 5, "Fan:");
    OLED_ShowString(7, 5, act->fan ? "ON " : "OFF");
    OLED_ShowString(11, 5, "Mode:");
    OLED_ShowString(18, 5, (g_sys_status.mode == MODE_AUTO) ? "AUTO" : "MANU");

    /* 第7行: WiFi + MQTT状态 */
    OLED_ShowString(0, 6, "WiFi:");
    OLED_ShowString(5, 6, g_sys_status.wifi_connected ? "OK" : "--");
    OLED_ShowString(9, 6, "MQTT:");
    OLED_ShowString(14, 6, g_sys_status.mqtt_connected ? "OK" : "--");

    /* 第8行: 灌溉统计 */
    OLED_ShowString(0, 7, "UP:");
    char uptime[8];
    snprintf(uptime, sizeof(uptime), "%lus", (unsigned long)g_sys_status.uptime_seconds);
    OLED_ShowString(3, 7, uptime);
}
